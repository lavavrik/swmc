/**
 * Regenerates the bundled copy of the game's monitor font.
 *
 * The app reads the font straight from a player's installation when they point
 * it at one; this is the fallback for everyone else, and it uses the same
 * parser so there is one description of the format rather than two.
 *
 *     npx tsx scripts/extract-tiny-font.ts [path-to-rom/graphics/fonts]
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { parseTinyFont } from '../src/lua/tinyFontFile'

const DEFAULT_FONTS = join(
  process.env.HOME ?? '',
  'Library/Application Support/Steam/steamapps/common/Stormworks',
  'stormworks.app/Contents/Resources/rom/graphics/fonts',
)

const fonts = process.argv[2] ?? DEFAULT_FONTS
const out = join(process.cwd(), 'src/lua/tinyFont.generated.ts')

const font = parseTinyFont(
  readFileSync(join(fonts, 'tiny.xml'), 'utf8'),
  new Uint8Array(readFileSync(join(fonts, 'tiny_0.txtr'))),
)

const entries = Object.entries(font.glyphs)
  .sort(([a], [b]) => Number(a) - Number(b))
  .map(
    ([id, g]) => `  ${id}: { w: ${g.w}, h: ${g.h}, xo: ${g.xo}, yo: ${g.yo}, rows: [${g.rows}] },`,
  )
  .join('\n')

writeFileSync(
  out,
  `/**
 * The pixel font the game draws monitors with — "${font.face}", ${Object.keys(font.glyphs).length} glyphs.
 *
 * Generated by scripts/extract-tiny-font.ts from a Stormworks installation.
 * Do not edit by hand; re-run the script instead.
 *
 * Each glyph is one number per row, bit 0 being the leftmost pixel.
 */
export interface TinyGlyph {
  readonly w: number
  readonly h: number
  /** Offset from the drawing position to the glyph's top-left corner. */
  readonly xo: number
  readonly yo: number
  readonly rows: readonly number[]
}

/** Every glyph is this many pixels wide, including the gap after it. */
export const TINY_ADVANCE = ${font.advance}
export const TINY_LINE_HEIGHT = ${font.lineHeight}

export const TINY_GLYPHS: Readonly<Record<number, TinyGlyph>> = {
${entries}
}
`,
  'utf8',
)

console.log(`${Object.keys(font.glyphs).length} glyphs from "${font.face}" written to ${out}`)
