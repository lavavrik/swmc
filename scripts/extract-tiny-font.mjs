/**
 * Extracts the pixel font Stormworks draws monitors with.
 *
 * The game ships it as a BMFont pair: `tiny.xml` describing 95 glyphs, and
 * `tiny_0.txtr` holding a 64x64 page — a 25-byte header followed by RGBA
 * pixels, magenta where there is nothing and white where the glyph is, stored
 * bottom-up as a TGA would be.
 *
 * Run it against your own installation to regenerate the font:
 *
 *     node scripts/extract-tiny-font.mjs [path-to-rom/graphics/fonts]
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

const DEFAULT_FONTS = join(
  process.env.HOME ?? '',
  'Library/Application Support/Steam/steamapps/common/Stormworks',
  'stormworks.app/Contents/Resources/rom/graphics/fonts',
)

const fonts = process.argv[2] ?? DEFAULT_FONTS
const out = join(process.cwd(), 'src/lua/tinyFont.generated.ts')

const xml = readFileSync(join(fonts, 'tiny.xml'), 'utf8')
const page = readFileSync(join(fonts, 'tiny_0.txtr'))

const attribute = (source, name) => {
  const match = source.match(new RegExp(`${name}="(-?\\d+)"`))
  if (!match) throw new Error(`missing ${name} in ${source}`)
  return Number(match[1])
}

const common = xml.match(/<common [^>]*\/>/)?.[0]
if (!common) throw new Error('no <common> element')
const width = attribute(common, 'scaleW')
const height = attribute(common, 'scaleH')
const lineHeight = attribute(common, 'lineHeight')

// The pixels are whatever is left after the header
const pixels = page.subarray(page.length - width * height * 4)
const lit = (x, y) => pixels[((height - 1 - y) * width + x) * 4 + 1] > 127

const glyphs = [...xml.matchAll(/<char [^>]*\/>/g)]
  .map((match) => {
    const a = (name) => attribute(match[0], name)
    const [gx, gy, gw, gh] = [a('x'), a('y'), a('width'), a('height')]
    // One number per row, bit 0 being the leftmost pixel
    const rows = Array.from({ length: gh }, (_, row) => {
      let bits = 0
      for (let col = 0; col < gw; col++) if (lit(gx + col, gy + row)) bits |= 1 << col
      return bits
    })
    return {
      id: a('id'),
      w: gw,
      h: gh,
      xo: a('xoffset'),
      yo: a('yoffset'),
      adv: a('xadvance'),
      rows,
    }
  })
  .sort((a, b) => a.id - b.id)

const advances = new Set(glyphs.map((g) => g.adv))
if (advances.size !== 1) throw new Error(`expected one advance, got ${[...advances]}`)

const face = xml.match(/face="([^"]*)"/)?.[1] ?? 'unknown'
const entries = glyphs
  .map((g) => `  ${g.id}: { w: ${g.w}, h: ${g.h}, xo: ${g.xo}, yo: ${g.yo}, rows: [${g.rows}] },`)
  .join('\n')

writeFileSync(
  out,
  `/**
 * The pixel font the game draws monitors with — "${face}", ${glyphs.length} glyphs.
 *
 * Generated by scripts/extract-tiny-font.mjs from a Stormworks installation.
 * Do not edit by hand; re-run the script instead.
 *
 * Each glyph is one number per row, bit 0 being the leftmost pixel.
 */
export interface TinyGlyph {
  readonly w: number
  readonly h: number
  /** Offset from the drawing position to the glyph's top-left corner. */
  readonly xo: number
  readonly yo: number
  readonly rows: readonly number[]
}

/** Every glyph is this many pixels wide, including the gap after it. */
export const TINY_ADVANCE = ${[...advances][0]}
export const TINY_LINE_HEIGHT = ${lineHeight}

export const TINY_GLYPHS: Readonly<Record<number, TinyGlyph>> = {
${entries}
}
`,
  'utf8',
)

console.log(`${glyphs.length} glyphs from "${face}" written to ${out}`)
