/**
 * Copies recipes/*.yaml (and their .md wiring notes) into
 * src/mcp/examples.generated.ts, so the bundled MCP server can hand them out
 * without the repository beside it.
 *
 *     npm run gen:mcp-examples
 */
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { format, resolveConfig } from 'prettier'

export interface Example {
  readonly name: string
  readonly recipe: string
  readonly notes?: string
}

export function readExamples(root: string): Example[] {
  const dir = join(root, 'recipes')
  return readdirSync(dir)
    .filter((f) => f.endsWith('.yaml'))
    .sort()
    .map((file) => {
      const name = file.slice(0, -'.yaml'.length)
      const notes = join(dir, `${name}.md`)
      return {
        name,
        recipe: readFileSync(join(dir, file), 'utf8'),
        ...(existsSync(notes) ? { notes: readFileSync(notes, 'utf8') } : {}),
      }
    })
}

function examplesSource(root: string): string {
  return `// Generated by scripts/gen-mcp-examples.ts from recipes/. Do not edit.
export interface Example {
  readonly name: string
  readonly recipe: string
  readonly notes?: string
}

export const EXAMPLES: readonly Example[] = ${JSON.stringify(readExamples(root), null, 2)}
`
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const root = process.cwd()
  const path = join(root, 'src/mcp/examples.generated.ts')
  writeFileSync(
    path,
    await format(examplesSource(root), { ...(await resolveConfig(path)), parser: 'typescript' }),
  )
}
